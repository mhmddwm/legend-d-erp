-- تأكيد وجود سلسلة الأصول (1 -> 11) قبل إضافة حساب المخزون، لنفس
-- احتياط migration 018/022 لقواعد البيانات المُبتدأة من schema.sql فقط.
INSERT INTO accounts (code, name_ar, name_en, account_type, nature, parent_code, opening_balance) VALUES
