('11', 'الأصول المتداولة',   'Current Assets', 'assets', 'مدين', '1',  0)
ON CONFLICT (code) DO NOTHING;

-- حساب المخزون الفعلي المُستخدم بكل منطق الترحيل الآلي بالكود — نظامي
-- لنفس سبب حماية 217/211: مُعتمَد عليه صراحة بالكود وليس مجرد اسم.
INSERT INTO accounts (code, name_ar, name_en, account_type, nature, parent_code, opening_balance, is_system) VALUES
('123', 'المخزون', 'Inventory', 'assets', 'مدين', '11', 0, TRUE)
ON CONFLICT (code) DO NOTHING;

UPDATE accounts SET is_system = TRUE WHERE code = '123';

-- حساب "113" القديم (إن وُجد من schema.sql القديم) لا يستخدمه أي كود
-- بالنظام؛ يُعطَّل تلقائياً فقط إذا لم يكن عليه أي قيد محاسبي مرحّل
-- بالفعل، حتى لا يظهر بجانب 123 كخيار مربك بشاشة القيود، دون التأثير
-- على أي بيانات تاريخية إن كان قد استُخدم فعلياً.
UPDATE accounts
SET is_active = FALSE
WHERE code = '113'
  AND NOT EXISTS (SELECT 1 FROM journal_entry_lines WHERE account_code = '113');

