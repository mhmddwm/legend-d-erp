-- =========================================================
-- LEGEND D ERP — Migration 034: ربط المنتج بقالب الوحدات
-- ---------------------------------------------------------
-- كان المنتج يحفظ اسم وحدته الأساسية فقط («حبة»)، دون أي إشارة إلى قالب الوحدات
-- الذي اختاره المستخدم، فتعرض شاشات (طلب الشراء...) وحدة «حبة» وحدها.
-- هذا العمود يحفظ اسم القالب مع المنتج.
--
-- Idempotent: آمن للتشغيل أكثر من مرة. العمود اختياري (NULL للمنتجات الحالية).
-- =========================================================

ALTER TABLE items
    ADD COLUMN IF NOT EXISTS unit_template VARCHAR(120);

COMMENT ON COLUMN items.unit_template IS 'اسم قالب الوحدات المرتبط بالمنتج (يُحفظ القالب نفسه حالياً في المتصفح)';